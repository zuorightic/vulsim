"""Contract for target coverage; physical cost library construction is step seven."""
import math
import hashlib
import re


def mapped_netlist_hash(text):
    """Ignore only generated banner/source locations; preserve connectivity."""
    text = re.sub(r'^/\* Generated by Yosys.*?\*/\n', '', text, flags=re.M)
    text = re.sub(r'\(\*\s*src\s*=\s*"[^"\n]*"\s*\*\)', '', text)
    text = '\n'.join(line.rstrip() for line in text.splitlines() if line.strip())+'\n'
    return hashlib.sha256(text.encode()).hexdigest()


def sensitivity_observation(points):
    """Measured equality is an observation, never permission to cover a gap."""
    keys = ['comparison_identity_sha256', 'mapped_netlist_sha256', 'cell_area_um2',
            'functional_cell_area_um2', 'sequential_area_um2', 'minimum_clock_period_ps']
    if len(points) < 2 or any(any(key not in point for key in keys) for point in points):
        raise ValueError('at least two complete identity/netlist/metric records required')
    identical = all(all(point[key] == points[0][key] for key in keys) for point in points[1:])
    return {'status':'equal_at_measured_points' if identical else 'differences_observed',
            'measured_targets_ps':sorted({p['abc_target_ps'] for p in points}),
            'family_target_insensitive':False, 'early_exit_authorized':False,
            'unmeasured_targets_covered':False}


def target_coverage(measured_targets_ps, requested_target_ps):
    targets = sorted(set(float(value) for value in measured_targets_ps))
    target = float(requested_target_ps)
    if not math.isfinite(target) or target <= 0 or any(not math.isfinite(t) or t <= 0 for t in targets):
        raise ValueError('targets must be finite and positive')
    if target in targets:
        return {'status':'covered', 'abc_target_ps':target, 'mode':'exact_measured_target'}
    return {'status':'uncovered', 'abc_target_ps':target,
            'reason':'unmeasured_target' if targets and targets[0] < target < targets[-1]
                     else 'outside_measured_targets', 'extrapolated':False}
